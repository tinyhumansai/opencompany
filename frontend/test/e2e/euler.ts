/**
 * The problem set, the host's own record, and the answer-reading this lane's
 * spec asserts on.
 *
 * Split out of `euler-live.spec.ts` for the reason `orchestration.ts` was split
 * out of the two specs it serves: what is a *gesture on the console* belongs
 * there and is shared by every lane, while what is a **read of this lane's
 * record** belongs here — the board rows, the transcript, the answers ledger,
 * and the table of problems whose answers are published.
 *
 * The card reads below deliberately duplicate a few lines of
 * `orchestration-live.spec.ts` rather than being hoisted into
 * `orchestration.ts`. That module states its own boundary at the top — console
 * gestures only, record reads belong beside the claim they settle — and moving
 * an HTTP read into it to save six lines would trade a stated design for a
 * de-duplication.
 */

/** A problem with a published answer, stated the way an operator would state it. */
export interface EulerProblem {
  /** The Project Euler number, which is also the key `PW_EULER_PROBLEM` takes. */
  id: string;
  /** The problem's published title, used in the goal and in the ledger row. */
  title: string;
  /**
   * The statement, in full.
   *
   * Handed over in the operator's message rather than fetched: this company
   * holds no `web` grant, so reading projecteuler.net is not a tool call away,
   * and a lane that let the lab browse for the statement would be testing its
   * browsing rather than its solving.
   *
   * That grant is not a network boundary and this lane does not pretend it is
   * — `shell` is granted and there is no sandbox
   * (`docs/spec/security/agent-isolation.md`). What makes the answer evidence
   * is `computed()` below: it has to have come out of a program that ran.
   */
  statement: string;
  /** The published answer, exactly. Compared as a string of digits. */
  answer: string;
  /** Why this one is in the set — what a run of it actually exercises. */
  why: string;
}

