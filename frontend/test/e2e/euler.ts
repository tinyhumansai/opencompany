// ── The host's own record ──────────────────────────────────────────────────

/** One card on the board, as the host holds it. */
export interface Card {
  id: string;
  title: string;
  column: string;
  stage?: string;
  assignee?: string;
}

export async function allCards(request: APIRequestContext): Promise<Card[]> {
  const response = await request.get(`${SCOPE}/tasks`);
  expect(response.ok(), `listing cards failed: ${response.status()}`).toBeTruthy();
  const body = await response.json();
  return (body.tasks ?? body) as Card[];
}

/**
 * Where a card is, in the one vocabulary that covers every case: the stage when
 * it has one, the phase otherwise (`stage` is omitted for a pending or done
 * card — issue #1512).
 */
export function landing(card: Card): string {
  return card.stage ?? card.column;
}

/**
 * The landings a run has actually stopped in.
 *
 * An allow-list of *stopped* states rather than "anything but `in_progress`",
 * which is the trap `orchestration-live.spec.ts` documents: a card nobody has
 * dispatched reads `pending`, so the loose form counts work that never started
 * as work that finished.
 */
export const SETTLED = ["in_review", "paused", "done"];

/** Cards waiting for an operator to start them. */
export function pending(cards: Card[]): Card[] {
  return cards.filter((card) => landing(card) === "pending");
}

/** One message in the main line, as `GET {scope}/chat/history` serves it. */
export interface Message {
  author: string;
  text: string;
  mine: boolean;
}

/**
 * The main line's transcript, from the host rather than from the DOM.
 *
 * The console renders a long reply progressively and elides tool steps, so a
 * `textContent()` read races the transcript it is trying to quote. The journal
 * does not.
 */
export async function transcript(request: APIRequestContext): Promise<Message[]> {
  const response = await request.get(`${SCOPE}/chat/history`);
  expect(response.ok(), `reading the transcript failed: ${response.status()}`).toBeTruthy();
  return (await response.json()) as Message[];
}

/** The company's last word — the newest message the operator did not write. */
export async function lastCompanyMessage(request: APIRequestContext): Promise<Message | undefined> {
  const messages = await transcript(request);
  return [...messages].reverse().find((message) => !message.mine);
}

/** One row of a ledger, as `GET {scope}/ledgers/<slug>` serves it. */
export interface Entry {
  id: string;
  status: string;
  title: string;
  fields: Record<string, string>;
}

/**
 * The rows of one ledger, or `[]` when the company has no such ledger.
 *
 * Tolerant on purpose: the answers ledger is *observed* by this lane and never
 * asserted on. Whether the lab filed its bookkeeping is worth reporting beside
 * the verdict, but a run that reached the right number and forgot to write it
 * down has still solved the problem, and a lane that failed it for that would
 * be measuring diligence rather than capability.
 */
export async function ledgerEntries(
  request: APIRequestContext,
  slug: string,
): Promise<Entry[]> {
  const response = await request.get(`${SCOPE}/ledgers/${slug}`);
  if (!response.ok()) return [];
  const body = await response.json();
  return ((body.entries ?? []) as Entry[]) ?? [];
}

// ── Reading a number out of a sentence ─────────────────────────────────────

/**
 * Every integer in a piece of text, with separators stripped.
 *
 * The lab is asked for a bare integer and usually gives one, but a model that
 * writes "756,872,327,473" or "**756872327473**" has answered correctly and a
 * comparison that missed it would be reporting on formatting. Thousands
 * separators are removed only when they are grouped as such, so a list like
 * "1, 2, 3" stays three numbers rather than becoming one.
 */
export function integersIn(text: string): string[] {
  // Grouped separators only: `\d{1,3}(,\d{3})+` accepts 756,872,327,473 and
  // leaves "1, 2, 3" as the three numbers it is.
  const found = text.match(/\d{1,3}(?:,\d{3})+|\d+/g) ?? [];
  return found.map((token) => token.replace(/,/g, ""));
}

/** Whether a piece of text states `answer` as one of its numbers. */
export function states(text: string, answer: string): boolean {
  return integersIn(text).includes(answer);
}

// ── The operator's other job: answering approvals ──────────────────────────

/** One parked approval, as `GET {scope}/approvals` serves it. */
export interface Approval {
  id: string;
  /** The parked effect's dotted kind — `shell`, `run_workflow`, `record_entry`. */
  kind: string;
}

/**
 * Everything waiting on the operator right now.
 *
 * This lane cannot run without it, and finding that out is the most useful
 * thing its first run produced. The math-lab agreement explicitly calls
 * `request_approval` before `shell` or `run_workflow`, then waits; policy HITL
 * itself is disabled. So the parked card proves the agent followed the routed
 * computation boundary rather than relying on a host interception.
 *
 * So a lab that computes cannot be unattended, and a spec that only sent
 * messages was testing a company with one hand tied. The first run of this lane
 * passed anyway — the orchestrator was refused `shell` and `run_workflow`, did
 * the arithmetic in its own head, and got the published answer, which is
 * exactly the outcome `computed()` below now refuses to accept.
 */
export async function parked(request: APIRequestContext): Promise<Approval[]> {
  const response = await request.get(`${SCOPE}/approvals`);
  if (!response.ok()) return [];
  return (await response.json()) as Approval[];
}

/**
 * Approves everything parked, and reports what was approved.
 *
 * The operator's gesture, and an honest one to automate here: this company
 * holds no `web`, no `search` and no money-spending tool, so the only thing it
 * can ask permission for is to run a program in its own sandbox — which is the
 * work that was asked for. Nothing is ever denied; a lane that denied would be
 * testing the refusal path, which is a different spec.
 *
 * `detach` matters. Without it the POST holds open for the whole follow-up
 * turn — minutes, on a reasoning rung — and the poll that called it would time
 * out waiting on the thing it just authorised. Detached, the verdict is durable
 * when this returns and the continuation arrives on the event stream.
 */
export async function approveAll(request: APIRequestContext): Promise<string[]> {
  const waiting = await parked(request);
  const approved: string[] = [];
  for (const approval of waiting) {
    const response = await request.post(`${SCOPE}/approvals/${approval.id}`, {
      data: { verdict: "approve", detach: true },
    });
    if (response.ok()) approved.push(approval.kind);
  }
  return approved;
}

/**
 * Whether a list of approved effect kinds shows the lab actually **ran**
 * something.
 *
 * The one method claim this lane makes, and it is not fastidiousness about
 * process. Every published Project Euler answer is in a model's training data,
 * so "the company said 756872327473" is satisfied by recall — and a lane that
 * accepted recall would report green on a company whose sandbox, tool belt and
 * whole roster had stopped working. Requiring that a program was actually run
 * is what separates the claim "this company can solve problems" from "this
 * model has seen this problem".
 *
 * It is also the *only* thing separating them. Withholding the `web` grant
 * removes the obvious shortcut but closes no network — `shell` is granted and
 * there is no sandbox (`docs/spec/security/agent-isolation.md`) — so "it
 * cannot have looked the answer up" is not a claim this lane is entitled to
 * make. "It produced the answer by running something" is.
 *
 * Deliberately not stricter than that. *Which* teammate ran it, in what
 * language, after how many attempts, and whether the answer was also filed on a
 * ledger are all left alone.
 */
export function computed(approvedKinds: string[]): boolean {
  return approvedKinds.some((kind) => kind.includes("shell") || kind.includes("run_workflow"));
}
