/** Which problem this run is pointed at. `PW_EULER_PROBLEM`, default 100. */
export function chosenProblem(): EulerProblem {
  const key = (process.env.PW_EULER_PROBLEM || "100").trim();
  const problem = EULER_PROBLEMS[key];
  if (!problem) {
    throw new Error(
      `PW_EULER_PROBLEM=${key} names no problem in this lane's set. ` +
        `Known: ${Object.keys(EULER_PROBLEMS).join(", ")}. Add it to euler.ts with its ` +
        `published answer — a problem whose answer this lane does not know is a lane ` +
        `that cannot report pass or fail.`,
    );
  }
  return problem;
}

